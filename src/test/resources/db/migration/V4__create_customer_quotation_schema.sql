CREATE TABLE PEDCTA (
    CODEMP INTEGER NOT NULL,
    DTERES DATE NOT NULL,
    NUMRES INTEGER NOT NULL,
    CODCLI INTEGER NOT NULL,
    SITCTA VARCHAR(10),
    TOTGER NUMERIC(15, 2),
    TOTITE NUMERIC(15, 2),
    TOTIPI NUMERIC(15, 2),
    TOTICM NUMERIC(15, 2),
    TOTPIS NUMERIC(15, 2),
    TOTCOF NUMERIC(15, 2),
    TOTSUB NUMERIC(15, 2),
    TOTDESCINC NUMERIC(15, 2),
    TOTFRT NUMERIC(15, 2),
    TOTSEG NUMERIC(15, 2),
    TOTOUTDESP NUMERIC(15, 2),
    CODVEN INTEGER,
    CODATD INTEGER,
    REGTRB INTEGER,
    CODPFA VARCHAR(20),
    SENT_TO_WEBSERVICE SMALLINT,
    CONSTRAINT PK_PEDCTA PRIMARY KEY (CODEMP, DTERES, NUMRES),
    CONSTRAINT FK_PEDCTA_FINCLI FOREIGN KEY (CODCLI) REFERENCES FINCLI (CODCLI)
);
